export function getHelpGuideHi(slug: string) {
  return HELP_GUIDES_HI.find((guide) => guide.slug === slug) ?? null;
}

export function hindiHelpSlugsMatchEnglish() {
  const en = HELP_GUIDES.map((guide) => guide.slug).sort();
  const hi = HELP_GUIDES_HI.map((guide) => guide.slug).sort();
  return en.length === hi.length && en.every((slug, i) => slug === hi[i]);
}
